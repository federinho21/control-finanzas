import { Annotation, END, START, StateGraph } from '@langchain/langgraph'
import type { ProposedPlan } from '~~/shared/types/plan'
import type { ProposedTask } from '~~/shared/types/task'
import { runDataOperation } from './data-agent'
import { answerWithRag } from './knowledge'
import { generateProposedTasks } from './planner'
import { generateProposedPlan } from './strategy-planner'
import { detectIntent, type AgentIntent } from './supervisor'
import { savePendingPlan, savePendingTasks } from './state-store'
import { judgeTaskCompletion } from './judge'
import { generateRetrospective } from './retrospective'
import { logger } from '~~/server/utils/logger'

/**
 * Defines the shared state schema passed between all LangGraph nodes in the agent workflow.
 * Each field uses `Annotation<T>` so LangGraph can track and merge partial state updates across nodes.
 * 
 * @property sessionId — Identifies the user's chat session; used to look up pending plans in the state store.
 * @property message — The original user message for the current turn.
 * @property action — Optional HITL action submitted by the frontend (approve, confirm delete, status update, etc.).
 * @property intent — Output of the supervisor node; contains the route, operation, and any extracted entity IDs.
 * @property response — The final text response to display in the chat.
 * @property proposedTasks — Tasks generated by the planner, awaiting user approval.
 * @property proposedPlan — Full Rock/Sprint/Task plan generated by strategy, awaiting user approval.
 * @property actionRequest — Prompt sent to the frontend requesting a HITL confirmation or status picker.
 * @property refreshBacklog — When true, the frontend should re-fetch the Quarter Board data.
 * @property judgeWarning — Non-null when the LLM-as-a-Judge detects a completed task is inconsistent with documents.
 * @property guardrailError — Non-null when a data operation violates a business rule guardrail.
 */
const AgentState = Annotation.Root({
  sessionId: Annotation<string>,
  message: Annotation<string>,
  action: Annotation<{ type: string; actionId?: string; payload?: Record<string, unknown> } | null>,
  intent: Annotation<AgentIntent | null>,
  response: Annotation<string>,
  proposedTasks: Annotation<ProposedTask[] | null>,
  proposedPlan: Annotation<ProposedPlan | null>,
  actionRequest: Annotation<
    | {
        type: 'approve_tasks' | 'confirm_delete' | 'approve_plan' | 'update_sprint_status' | 'update_task_status'
        actionId: string
        prompt: string
        entityId?: string
        statusOptions?: Array<{ label: string; value: string; color: string }>
      }
    | null
  >,
  refreshBacklog: Annotation<boolean>,
  judgeWarning: Annotation<string | null>,
  guardrailError: Annotation<string | null>
})

/**
 * LangGraph node that detects user intent by routing through classification.
 * Reads from state: message, action
 * Writes to state: intent, response, proposedTasks, proposedPlan, actionRequest, refreshBacklog
 * @param state - The current agent state
 * @returns Updated state with detected intent and clarification if needed
 */
const supervisorNode = async (state: typeof AgentState.State) => {
  logger.info('Graph', `supervisorNode - session=${state.sessionId} message="${state.message.slice(0, 80)}"`)

  const intent = await detectIntent({
    message: state.message,
    sessionId: state.sessionId,
    action: state.action ?? undefined
  })

  logger.info('Graph', `supervisor routed to "${intent.route}" op="${intent.operation ?? 'none'}" confidence=${intent.confidence ?? '-'}`)

  // When routing ends early, return a direct clarification prompt for the chat response.
  const response = intent.route === 'END'
    ? (intent.clarificationQuestion
      || 'Could you clarify what you want to do next? I can generate a plan, plan tasks, query knowledge, or list backlog on request.')
    : state.response

  return {
    intent,
    response,
    proposedTasks: null,
    proposedPlan: null,
    actionRequest: null,
    refreshBacklog: false
  }
}

/**
 * LangGraph node that generates a complete strategic plan when user doesn't provide Rock/Sprint IDs.
 * Reads from state: message, sessionId
 * Writes to state: response, proposedPlan, actionRequest
 * @param state - The current agent state
 * @returns Updated state with the proposed plan and approval action request
 */
const strategyNode = async (state: typeof AgentState.State) => {
  logger.info('Graph', 'strategyNode - generating full plan')

  const plan = await generateProposedPlan({
    message: state.message
  })

  const actionId = crypto.randomUUID()
  savePendingPlan(actionId, {
    sessionId: state.sessionId,
    plan
  })

  return {
    response: 'A full plan preview is ready. Review it in the Quarter Board preview, then approve to persist it.',
    proposedPlan: plan,
    actionRequest: {
      type: 'approve_plan',
      actionId,
      prompt: 'Do you want to approve this full plan?'
    }
  }
}

/**
 * LangGraph node that generates proposed tasks for a specific Rock and Sprint.
 * Reads from state: message, intent (rockId, sprintId), sessionId
 * Writes to state: response, proposedTasks, actionRequest
 * @param state - The current agent state
 * @returns Updated state with proposed tasks and approval action request, or delegates to strategy
 */
const plannerNode = async (state: typeof AgentState.State) => {
  logger.info('Graph', `plannerNode - rock=${state.intent?.rockId} sprint=${state.intent?.sprintId}`)

  if (!state.intent) {
    return { response: 'Could not detect intent for planning.' }
  }

  // Without explicit IDs, treat the request as free-form planning and delegate to strategy.
  if (!state.intent.rockId || !state.intent.sprintId) {
    return strategyNode(state)
  }

  const tasks = await generateProposedTasks({
    message: state.message,
    rockId: state.intent.rockId,
    sprintId: state.intent.sprintId
  })

  const actionId = crypto.randomUUID()
  savePendingTasks(actionId, {
    sessionId: state.sessionId,
    rockId: state.intent.rockId,
    sprintId: state.intent.sprintId,
    tasks
  })

  return {
    response: `Generated ${tasks.length} proposed tasks. Review and approve them to save.`,
    proposedTasks: tasks,
    actionRequest: {
      type: 'approve_tasks',
      actionId,
      prompt: 'Do you want to approve these tasks?'
    }
  }
}

/**
 * LangGraph node that executes data operations (CRUD on rocks, sprints, tasks).
 * Reads from state: sessionId, intent (operation, rockId, sprintId, taskId, actionId, payload), message
 * Writes to state: response, refreshBacklog, actionRequest, guardrailError
 * @param state - The current agent state
 * @returns Updated state with operation result, confirmations, or status pickers
 */
const dataNode = async (state: typeof AgentState.State) => {
  logger.info('Graph', `dataNode - operation="${state.intent?.operation}"`)

  const resultAsAny = await runDataOperation({
    sessionId: state.sessionId,
    operation: state.intent?.operation,
    message: state.message,
    rockId: state.intent?.rockId,
    sprintId: state.intent?.sprintId,
    taskId: state.intent?.taskId,
    status: state.intent?.status,
    actionId: state.intent?.actionId,
    payload: state.intent?.payload
  }) as Record<string, unknown>

  let actionRequest: typeof AgentState.State['actionRequest'] = null

  if (resultAsAny.confirmation) {
    const confirmation = resultAsAny.confirmation as { actionId: string; prompt: string }
    actionRequest = {
      type: 'confirm_delete',
      actionId: confirmation.actionId,
      prompt: confirmation.prompt
    }
  } else if ((resultAsAny.statusPicker as Record<string, unknown> | undefined)?.entityType === 'sprint') {
    const statusPicker = resultAsAny.statusPicker as { entityId: string; entityType: string }
    const actionId = crypto.randomUUID()
    actionRequest = {
      type: 'update_sprint_status',
      actionId,
      prompt: typeof resultAsAny.message === 'string' ? resultAsAny.message : 'Please select the new sprint status.',
      entityId: statusPicker.entityId,
      statusOptions: [
        { label: 'Planned', value: 'planned', color: 'neutral' },
        { label: 'In Progress', value: 'in_progress', color: 'warning' },
        { label: 'Completed', value: 'completed', color: 'success' },
        { label: 'On Hold', value: 'on_hold', color: 'error' }
      ]
    }
  } else if ((resultAsAny.statusPicker as Record<string, unknown> | undefined)?.entityType === 'task') {
    const statusPicker = resultAsAny.statusPicker as { entityId: string; entityType: string }
    const actionId = crypto.randomUUID()
    actionRequest = {
      type: 'update_task_status',
      actionId,
      prompt: typeof resultAsAny.message === 'string' ? resultAsAny.message : 'Please select the new task status.',
      entityId: statusPicker.entityId,
      statusOptions: [
        { label: 'Pending', value: 'pending', color: 'neutral' },
        { label: 'In Progress', value: 'in_progress', color: 'warning' },
        { label: 'Completed', value: 'completed', color: 'success' }
      ]
    }
  }

  // For modify_plan, data-agent returns `response` (not `message`) and can include
  // proposedPlan + actionRequest directly.
  const responseText = typeof resultAsAny.response === 'string' ? resultAsAny.response : undefined
  const message = responseText ?? (typeof resultAsAny.message === 'string' ? resultAsAny.message : '')

  // Propagate proposedPlan when returned by modify_plan.
  const proposedPlan = resultAsAny.proposedPlan != null
    ? resultAsAny.proposedPlan as typeof AgentState.State['proposedPlan']
    : null

  // If modify_plan returned its own actionRequest (approve_plan), keep it.
  if (!actionRequest && resultAsAny.actionRequest != null) {
    actionRequest = resultAsAny.actionRequest as typeof AgentState.State['actionRequest']
  }

  // Detect whether the response signals a guardrail violation (business rule enforcement).
  const isGuardrailError = message.includes('Rule:')
    || message.includes('does not exist')
    || message.includes('not linked')
    || message.includes('must be between')

  return {
    response: message,
    proposedPlan,
    refreshBacklog: Boolean(resultAsAny.refreshBacklog),
    actionRequest,
    guardrailError: isGuardrailError ? message : null
  }
}

/**
 * LangGraph node that answers user questions using RAG (Retrieval-Augmented Generation).
 * Reads from state: message
 * Writes to state: response
 * @param state - The current agent state
 * @returns Updated state with RAG-generated answer
 */
const knowledgeNode = async (state: typeof AgentState.State) => {
  logger.info('Graph', `knowledgeNode - RAG query: "${state.message.slice(0, 80)}"`)
  const response = await answerWithRag(state.message)
  return { response }
}

/**
 * LangGraph node that verifies whether a completed task is consistent with uploaded documents.
 * Reads `intent.taskId` from state; writes `judgeWarning` with any detected inconsistency message.
 * @param state Current agent state.
 * @returns Partial state update with `judgeWarning` set to a warning string or null.
 */
const judgeNode = async (state: typeof AgentState.State) => {
  logger.info('Graph', `judgeNode - checking task=${state.intent?.taskId}`)

  const taskId = state.intent?.taskId
  if (!taskId) return { judgeWarning: null }
  
  const result = await judgeTaskCompletion(taskId)
  logger.info('Graph', `judgeNode - isConsistent=${result.isConsistent}${result.warning ? ' warning emitted' : ''}`)

  return {
    judgeWarning: result.isConsistent ? null : (result.warning ?? null)
  }
}

/**
 * LangGraph node that generates a sprint retrospective summary using an LLM.
 * Reads from state: intent (sprintId)
 * Writes to state: response
 * @param state - The current agent state
 * @returns Updated state with the retrospective summary as the response
 */
const retroNode = async (state: typeof AgentState.State) => {
  logger.info('Graph', `retroNode - sprint=${state.intent?.sprintId}`)

  const sprintId = state.intent?.sprintId
  if (!sprintId) {
    return { response: 'Please provide a Sprint ID (e.g., S-XXXX) to generate a retrospective.' }
  }
  const summary = await generateRetrospective(sprintId)
  return { response: summary }
}

const graph = new StateGraph(AgentState)
  .addNode('supervisor', supervisorNode)
  .addNode('planner', plannerNode)
  .addNode('strategy', strategyNode)
  .addNode('data', dataNode)
  .addNode('knowledge', knowledgeNode)
  .addNode('judge', judgeNode)
  .addNode('retro', retroNode)
  .addEdge(START, 'supervisor')
  .addConditionalEdges('supervisor', (state) => state.intent?.route ?? 'END', {
    planner: 'planner',
    strategy: 'strategy',
    data: 'data',
    knowledge: 'knowledge',
    retro: 'retro',
    END
  })
  .addEdge('planner', END)
  .addEdge('strategy', END)
  .addConditionalEdges('data', (state) => {
    // Route to judge when a task is marked completed, to verify consistency with uploaded documents.
    if (state.intent?.operation === 'update_task_status' 
        && (state.intent?.status === 'completed' || state.intent?.payload?.status === 'completed')) {
      return 'judge'
    }
    return 'END'
  }, {
    judge: 'judge',
    END
  })
  .addEdge('judge', END)
  .addEdge('knowledge', END)
  .addEdge('retro', END)
  .compile()

export interface RunGraphInput {
  sessionId: string
  message: string
  action?: { type: string; actionId?: string; payload?: Record<string, unknown> } | null
  onEvent?: (event: {
    type: 'status' | 'result'
    data: Record<string, unknown>
  }) => void
}

/**
 * Runs the LangGraph agent workflow and streams events.
 * @param input - Input containing session ID, message, action, and optional event callback
 * @returns The final agent state after graph execution
 * @throws Error if no final state is returned
 */
export async function runGraph(input: RunGraphInput) {
  logger.info('Graph', `runGraph START session=${input.sessionId}`)

  const stream = graph.streamEvents(
    {
      sessionId: input.sessionId,
      message: input.message,
      action: input.action ?? null,
      intent: null,
      response: '',
      proposedTasks: null,
      proposedPlan: null,
      actionRequest: null,
      refreshBacklog: false,
      judgeWarning: null,
      guardrailError: null
    },
    { version: 'v2' }
  )

  let finalState: typeof AgentState.State | null = null

  for await (const event of stream) {
    if (event.event === 'on_chain_start' && event.name) {
      input.onEvent?.({
        type: 'status',
        data: { message: `${event.name} running...` }
      })
    }

    if (event.event === 'on_chain_end' && event.data?.output) {
      finalState = event.data.output as typeof AgentState.State
    }
  }

  if (!finalState) {
    throw new Error('No final state returned by graph')
  }

  input.onEvent?.({
    type: 'result',
    data: {
      message: finalState.response,
      proposedTasks: finalState.proposedTasks,
      proposedPlan: finalState.proposedPlan,
      actionRequest: finalState.actionRequest,
      refreshBacklog: finalState.refreshBacklog
    }
  })

  logger.info('Graph', `runGraph END session=${input.sessionId}`)

  return finalState
}
